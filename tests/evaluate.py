"""Reproduce the numbers in docs/EVALUATION.md.

    python tests/evaluate.py                       # labelled corpora only (tuning + held-out)
    python tests/evaluate.py path/to/skills ...    # also scan public folders and list every non-PASS file

Labelled corpora: each sample has an expected verdict (PASS / REVIEW / FAIL). A sample is "caught" when a
malicious sample gets REVIEW or FAIL, and a "false alarm" when a benign sample gets anything but PASS.
Public folders have no labels: every REVIEW/FAIL file is printed so a human can judge it.
"""

from __future__ import annotations

import base64
import json
import sys
import time
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from hexbane.scanner import collect_files, scan_files  # noqa: E402


def decode(files: dict) -> list[tuple[str, str]]:
    return [(name, base64.b64decode(data).decode("utf-8")) for name, data in files.items()]


def labelled(name: str) -> list[str]:
    data = json.loads((ROOT / "corpus" / f"{name}.json").read_text(encoding="utf-8"))
    lines = [f"### {name} ({len(data['samples'])} samples)", "", "| sample | set | expected | got | rules |", "|---|---|---|---|---|"]
    exact = caught = malicious = alarms = benign = 0
    for sample in data["samples"]:
        report = scan_files(decode(sample["files"]))
        got = report["verdict"]
        rules = sorted({finding["rule"] for finding in report["findings"]})
        exact += got == sample["expected"]
        if sample["set"] == "benign":
            benign += 1
            alarms += got != "PASS"
        else:
            malicious += 1
            caught += got != "PASS"
        mark = "" if got == sample["expected"] else " **(differs)**"
        lines.append(f"| {sample['id']} | {sample['set']} | {sample['expected']} | {got}{mark} | {', '.join(rules) or '-'} |")
    lines += ["", f"Exact verdict: {exact}/{len(data['samples'])} - malicious caught: {caught}/{malicious} - "
                  f"benign false alarms: {alarms}/{benign}", ""]
    return lines


def public(folder: Path) -> list[str]:
    skipped: list = []
    started = time.perf_counter()
    files = collect_files(folder, skipped)
    report = scan_files(files, skipped)
    seconds = time.perf_counter() - started
    size = sum(len(text.encode("utf-8")) for _, text in files)
    per_file = Counter(entry["verdict"] for entry in report["files"])
    lines = [f"### {folder.name} ({len(files)} files, {size / 1e6:.1f} MB, {seconds:.1f} s)", "",
             f"Files: {per_file.get('PASS', 0)} PASS, {per_file.get('REVIEW', 0)} REVIEW, {per_file.get('FAIL', 0)} FAIL. "
             f"Skipped: {len(skipped)}.", ""]
    flagged = [entry for entry in report["files"] if entry["verdict"] != "PASS"]
    if flagged:
        lines += ["| file | verdict | rules |", "|---|---|---|"]
        for entry in flagged:
            rules = sorted({f["rule"] for f in report["findings"] if f["file"] == entry["path"]})
            lines.append(f"| {entry['path']} | {entry['verdict']} | {', '.join(rules)} |")
        lines.append("")
    return lines


def obfuscation() -> list[str]:
    """Each malicious tuning sample rewritten with one evasion trick (corpus/obfuscated.json).

    "Rules kept" counts the rules the original, undisguised sample triggers that still fire on the disguised copy.
    Runs twice: with the unfolding pass switched off (how v0.1 behaved) and on.
    """
    import hexbane.scanner as scanner_module

    data = json.loads((ROOT / "corpus" / "obfuscated.json").read_text(encoding="utf-8"))
    sources = {s["id"]: s for s in json.loads((ROOT / "corpus" / "tuning.json").read_text(encoding="utf-8"))["samples"]}
    target_rules = {}
    for sample in data["samples"]:
        source = sources[sample["source"]]
        target_rules[sample["id"]] = {f["rule"] for f in scan_files(decode(source["files"]))["findings"]}

    def measure() -> dict:
        per_trick: dict = {}
        for sample in data["samples"]:
            report = scan_files(decode(sample["files"]))
            got = {f["rule"] for f in report["findings"]}
            row = per_trick.setdefault(sample["trick"], {"samples": 0, "flagged": 0, "kept": 0, "targets": 0})
            row["samples"] += 1
            row["flagged"] += report["verdict"] != "PASS"
            row["kept"] += len(target_rules[sample["id"]] & got)
            row["targets"] += len(target_rules[sample["id"]])
        return per_trick

    original_fold = scanner_module.scan_folded
    scanner_module.scan_folded = lambda scan, clean: None
    try:
        before = measure()
    finally:
        scanner_module.scan_folded = original_fold
    after = measure()

    lines = [f"### obfuscated ({len(data['samples'])} samples, generated by tests/obfuscate.py)", "",
             "| trick | samples | flagged without unfolding | flagged with unfolding | rules kept without | rules kept with |",
             "|---|---|---|---|---|---|"]
    totals = {key: 0 for key in ("samples", "flagged_before", "flagged_after", "kept_before", "kept_after", "targets")}
    for trick in sorted(after):
        b, a = before[trick], after[trick]
        lines.append(f"| {trick} | {a['samples']} | {b['flagged']}/{b['samples']} | {a['flagged']}/{a['samples']} | "
                     f"{b['kept']}/{b['targets']} | {a['kept']}/{a['targets']} |")
        totals["samples"] += a["samples"]
        totals["flagged_before"] += b["flagged"]
        totals["flagged_after"] += a["flagged"]
        totals["kept_before"] += b["kept"]
        totals["kept_after"] += a["kept"]
        totals["targets"] += a["targets"]
    lines.append(f"| **all** | {totals['samples']} | {totals['flagged_before']}/{totals['samples']} | "
                 f"{totals['flagged_after']}/{totals['samples']} | {totals['kept_before']}/{totals['targets']} | "
                 f"{totals['kept_after']}/{totals['targets']} |")
    lines.append("")
    return lines


def main() -> int:
    out = ["## Labelled corpora", ""]
    out += labelled("tuning")
    out += labelled("heldout")
    out += obfuscation()
    if len(sys.argv) > 1:
        out += ["## Public folders (unlabelled)", ""]
        for arg in sys.argv[1:]:
            out += public(Path(arg))
    print("\n".join(out))
    return 0


if __name__ == "__main__":
    sys.exit(main())
